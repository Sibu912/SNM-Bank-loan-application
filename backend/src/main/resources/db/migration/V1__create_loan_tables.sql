-- V1__create_loan_tables.sql
-- Creates the three tables for the SNM Bank loan service.
-- Written for PostgreSQL. Also runs on H2 (MODE=PostgreSQL) for tests.

CREATE TABLE applicant (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(10)  NOT NULL,
    given_name   VARCHAR(100) NOT NULL,
    surname      VARCHAR(100) NOT NULL,
    gender       VARCHAR(10)  NOT NULL,
    street       VARCHAR(150) NOT NULL,
    suburb       VARCHAR(100) NOT NULL,
    province     VARCHAR(50)  NOT NULL,
    postal_code  VARCHAR(4)   NOT NULL,
    created_at   TIMESTAMP    NOT NULL
);

CREATE TABLE loan_application (
    id                          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_number            VARCHAR(20)   UNIQUE,
    applicant_id                BIGINT        NOT NULL REFERENCES applicant (id),
    loan_purpose                VARCHAR(20)   NOT NULL,
    loan_amount_band            VARCHAR(30)   NOT NULL,
    term_years                  INTEGER       NOT NULL CHECK (term_years IN (5, 10, 15, 20, 25, 30)),
    income_band                 VARCHAR(30)   NOT NULL,
    estimated_monthly_repayment NUMERIC(12,2) NOT NULL,
    affordability_result        VARCHAR(10)   NOT NULL,
    status                      VARCHAR(20)   NOT NULL,
    channel                     VARCHAR(10)   NOT NULL,
    created_at                  TIMESTAMP     NOT NULL,
    updated_at                  TIMESTAMP     NOT NULL
);

CREATE INDEX idx_loan_application_status    ON loan_application (status);
CREATE INDEX idx_loan_application_applicant ON loan_application (applicant_id);

CREATE TABLE application_status_history (
    id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_application_id  BIGINT       NOT NULL REFERENCES loan_application (id),
    from_status          VARCHAR(20),
    to_status            VARCHAR(20)  NOT NULL,
    note                 VARCHAR(255),
    changed_by           VARCHAR(50)  NOT NULL,
    changed_at           TIMESTAMP    NOT NULL
);

CREATE INDEX idx_status_history_application ON application_status_history (loan_application_id);
